ROOT = Path(__file__).resolve().parents[2]
REGISTRY_PATH = "docs/agent_rules/docs_registry.json"
SUPPORTED_SCHEMA_VERSION = 1
TEXT_SUFFIXES = {
    "",
    ".cfg",
    ".csv",
    ".gitignore",
    ".json",
    ".jsonl",
    ".md",
    ".ps1",
    ".py",
    ".sh",
    ".sql",
    ".toml",
    ".txt",
    ".yaml",
    ".yml",
}
ALLOWED_DOCUMENT_TYPES = {
    "canonical_spec",
    "operational_guide",
    "active_design",
    "generated_view",
    "audit_record",
    "migration_record",
    "historical_snapshot",
    "config_explanation",
    "unknown",
}
ALLOWED_LIFECYCLE_STATUSES = {
    "active",
    "generated",
    "historical",
    "archive_candidate",
    "delete_candidate",
    "needs_human_confirmation",
}
ALLOWED_PROPOSED_ACTIONS = {"keep", "regenerate_only", "archive", "delete", "review"}
DATE_SUFFIX_RE = re.compile(r"(?:^|[_-])((?:19|20)\d{2}[-_]?\d{2}[-_]?\d{2}|(?:19|20)\d{6})(?:$|[_-])")
MARKDOWN_LINK_RE = re.compile(r"\[[^\]]+\]\(([^)]+)\)")
DOCS_LITERAL_RE = re.compile(r"docs/[^\s'\"`)>]+")
WRITE_MARKERS = ("write_text", ".write(", "open(", "with open", "Path(", "output", "export")
AUTO_GENERATED_MARKERS = ("自动生成", "auto-generated", "generated by", "由脚本生成")
GOVERNANCE_REFERENCE_SOURCES = {
    "docs/agent_rules/docs_registry.json",
    "docs/文档治理盘点报告.md",
}


def _repo_root() -> Path:
    return ROOT.resolve()


def normalize_repo_path(path: str | Path) -> str:
    return str(path).replace("\\", "/").strip()


def _repo_relative(path: Path) -> str:
    return normalize_repo_path(path.resolve(strict=False).relative_to(_repo_root()))


def _resolve_repo_path(path: str | Path) -> Path:
    candidate = Path(path)
    if not candidate.is_absolute():
        candidate = _repo_root() / candidate
    resolved = candidate.resolve(strict=False)
    try:
        resolved.relative_to(_repo_root())
    except ValueError as exc:
        raise ValueError(f"path escapes repo root: {path}") from exc
    return resolved


def _ensure_tmp_output(output: str | None) -> Path | None:
    if not output:
        return None
    target = _resolve_repo_path(output)
    if not _repo_relative(target).startswith(".tmp/"):
        raise ValueError(f"output must be under .tmp/: {output}")
    target.parent.mkdir(parents=True, exist_ok=True)
    return target


def _emit_stdout(text: str) -> None:
    sys.stdout.buffer.write(text.encode("utf-8"))


def _emit_stderr(text: str) -> None:
    sys.stderr.buffer.write((text + "\n").encode("utf-8"))


def git_output_bytes(*args: str, check: bool = True) -> bytes:
    result = subprocess.run(
        ["git", "-c", "core.quotepath=false", *args],
        cwd=_repo_root(),
        capture_output=True,
        text=False,
        check=False,
    )
    if check and result.returncode != 0:
        stderr = result.stderr.decode("utf-8", errors="replace").strip()
        raise RuntimeError(f"git {' '.join(args)} failed: {stderr}")
    return result.stdout


def git_output_text(*args: str, check: bool = True) -> str:
    return git_output_bytes(*args, check=check).decode("utf-8")


def git_lines(*args: str) -> list[str]:
    return [normalize_repo_path(line) for line in git_output_text(*args).splitlines() if line.strip()]


def _git_blob(ref: str, path: str) -> bytes:
    return git_output_bytes("show", f"{ref}:{path}")


def _is_text_path(path: str) -> bool:
    suffix = Path(path).suffix.lower()
    if Path(path).name == ".gitignore":
        return True
    return suffix in TEXT_SUFFIXES


def _decode_text(data: bytes) -> str | None:
    try:
        return data.decode("utf-8-sig")
    except UnicodeDecodeError:
        return None


def _normalized_text(text: str) -> str:
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    return "\n".join(line.rstrip() for line in lines).strip() + "\n"


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _title(text: str | None) -> str | None:
    if not text:
        return None
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip() or None
    return None


def _date_suffix(path: str) -> str | None:
    match = DATE_SUFFIX_RE.search(Path(path).stem)
    return match.group(1) if match else None


def _tracked_docs(ref: str) -> list[str]:
    return sorted(path for path in git_lines("ls-tree", "-r", "--name-only", ref, "--", "docs") if path.startswith("docs/"))


def _tracked_reference_files(ref: str) -> list[str]:
    candidates: list[str] = []
    for path in git_lines("ls-tree", "-r", "--name-only", ref):
        if path.startswith((".tmp/", "exports/", "data/configs/")):
            continue
        if path in {"README.md", "AGENTS.md"}:
            candidates.append(path)
        elif path.startswith(("docs/", "scripts/", "tests/", ".github/")):
            candidates.append(path)
        elif "/" not in path and _is_text_path(path):
            candidates.append(path)
    return sorted(dict.fromkeys(candidates))


def _read_ref_text(ref: str, path: str) -> str | None:
    if not _is_text_path(path):
        return None
    return _decode_text(_git_blob(ref, path))


def _markdown_link_targets(text: str) -> list[str]:
    targets: list[str] = []
    for raw in MARKDOWN_LINK_RE.findall(text):
        target = raw.split("#", 1)[0].strip()
        if not target or target.startswith(("http://", "https://", "mailto:")):
            continue
        targets.append(normalize_repo_path(target))
    return targets


def _candidate_reference_paths(source_path: str, text: str) -> set[str]:
    refs: set[str] = set()
    source_dir = Path(source_path).parent.as_posix()
    for target in _markdown_link_targets(text):
        normalized_target = normalize_repo_path(posixpath.normpath(target))
        if target.startswith("docs/"):
            refs.add(normalized_target)
        elif target.endswith(".md") or target.startswith("../"):
            refs.add(normalize_repo_path(posixpath.normpath(posixpath.join(source_dir, target))))
    refs.update(match.rstrip(".,;:，。；：") for match in DOCS_LITERAL_RE.findall(text))
    return refs


def _build_reference_maps(
    ref: str, docs_paths: list[str]
) -> tuple[dict[str, list[str]], dict[str, list[str]], dict[str, list[str]], dict[str, list[str]], dict[str, list[str]]]:
    docs_set = set(docs_paths)
    inbound: dict[str, set[str]] = {path: set() for path in docs_paths}
    governance: dict[str, set[str]] = {path: set() for path in docs_paths}
    weak: dict[str, set[str]] = {path: set() for path in docs_paths}
    tests: dict[str, set[str]] = {path: set() for path in docs_paths}
    generators: dict[str, set[str]] = {path: set() for path in docs_paths}
    basenames: dict[str, list[str]] = defaultdict(list)
    for doc_path in docs_paths:
        basenames[Path(doc_path).name].append(doc_path)

    for source_path in _tracked_reference_files(ref):
        text = _read_ref_text(ref, source_path)
        if text is None:
            continue
        target_map = governance if source_path in GOVERNANCE_REFERENCE_SOURCES else inbound
        explicit_refs = _candidate_reference_paths(source_path, text)
        for target_ref in explicit_refs:
            normalized = normalize_repo_path(target_ref)
            if normalized in docs_set and normalized != source_path:
                target_map[normalized].add(source_path)
                if source_path in GOVERNANCE_REFERENCE_SOURCES:
                    continue
                if source_path.startswith("tests/"):
                    tests[normalized].add(source_path)
                if source_path.startswith(("scripts/", "tests/")) and any(marker in text for marker in WRITE_MARKERS):
                    generators[normalized].add(source_path)
        for name, matching_docs in basenames.items():
            if name in text:
                for doc_path in matching_docs:
                    if doc_path != source_path and source_path not in inbound[doc_path]:
                        weak[doc_path].add(source_path)
        if source_path.startswith(("scripts/", "tests/")) and any(marker in text for marker in WRITE_MARKERS):
            for doc_path in docs_paths:
                if doc_path in text or Path(doc_path).name in text:
                    generators[doc_path].add(source_path)

    return (
        {path: sorted(values) for path, values in inbound.items()},
        {path: sorted(values) for path, values in governance.items()},
        {path: sorted(values) for path, values in weak.items()},
        {path: sorted(values) for path, values in tests.items()},
        {path: sorted(values) for path, values in generators.items()},
    )


def _group_values(values: dict[str, str | None], prefix: str) -> dict[str, str | None]:
    reverse: dict[str, list[str]] = defaultdict(list)
    for path, value in values.items():
        if value:
            reverse[value].append(path)
    groups: dict[str, str | None] = {path: None for path in values}
    index = 1
    for _, paths in sorted(reverse.items(), key=lambda item: sorted(item[1])):
        if len(paths) < 2:
            continue
        group_id = f"{prefix}{index:03d}"
        index += 1
        for path in paths:
            groups[path] = group_id
    return groups


def build_inventory(ref: str = "origin/GPT") -> dict[str, Any]:
    docs_paths = _tracked_docs(ref)
    inbound, governance, weak, referenced_by_tests, generator_candidates = _build_reference_maps(ref, docs_paths)
    items: list[dict[str, Any]] = []
    exact_values: dict[str, str | None] = {}
    normalized_values: dict[str, str | None] = {}
    title_values: dict[str, str | None] = {}
    extension_counts: Counter[str] = Counter()
    directory_counts: Counter[str] = Counter()
    generated_count = 0
    markdown_count = 0
    date_suffix_count = 0

    for path in docs_paths:
        data = _git_blob(ref, path)
        suffix = Path(path).suffix.lower()
        extension_counts[suffix or "<none>"] += 1
        parts = Path(path).parts
        directory_counts["/".join(parts[:2]) if len(parts) > 1 else "docs"] += 1
        markdown_count += int(suffix == ".md")
        date_suffix = _date_suffix(path)
        date_suffix_count += int(bool(date_suffix))
        text = _decode_text(data) if _is_text_path(path) else None
        normalized_hash = _sha256(_normalized_text(text).encode("utf-8")) if text is not None else None
        title = _title(text)
        generated_marker = bool(text and any(marker in text for marker in AUTO_GENERATED_MARKERS))
        generated_count += int(generated_marker or bool(generator_candidates[path]))
        exact_values[path] = _sha256(data)
        normalized_values[path] = normalized_hash
        title_values[path] = title
        items.append(
            {
                "date_suffix": date_suffix,
                "exact_duplicate_group": None,
                "generator_candidates": generator_candidates[path],
                "generated_marker": generated_marker,
                "governance_references": governance[path],
                "inbound_references": inbound[path],
                "is_text": text is not None,
                "line_count": len(text.splitlines()) if text is not None else None,
                "normalized_duplicate_group": None,
                "normalized_text_sha256": normalized_hash,
                "path": path,
                "referenced_by_tests": referenced_by_tests[path],
                "same_title_group": None,
                "sha256": _sha256(data),
                "size_bytes": len(data),
                "suffix": suffix,
                "title": title,
                "weak_reference_candidates": weak[path],
            }
        )

    exact_groups = _group_values(exact_values, "exact-")
    normalized_groups = _group_values(normalized_values, "norm-")
    title_groups = _group_values(title_values, "title-")
    for item in items:
        item["exact_duplicate_group"] = exact_groups[item["path"]]
        item["normalized_duplicate_group"] = normalized_groups[item["path"]]
        item["same_title_group"] = title_groups[item["path"]]

    return {
        "documents": sorted(items, key=lambda item: item["path"]),
        "ref": ref,
        "ref_sha": git_output_text("rev-parse", ref).strip(),
        "schema_version": 1,
        "stats": {
            "date_suffix_files": date_suffix_count,
            "extension_counts": dict(sorted(extension_counts.items())),
            "first_level_counts": dict(sorted(directory_counts.items())),
            "generated_candidate_files": generated_count,
            "markdown_files": markdown_count,
            "referenced_files": sum(1 for item in items if item["inbound_references"]),
            "total_files": len(items),
            "unreferenced_files": sum(1 for item in items if not item["inbound_references"]),
        },
    }


def _json_text(payload: Any) -> str:
    return json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def write_json(payload: Any, output: str | None) -> None:
    text = _json_text(payload)
    target = _ensure_tmp_output(output)
    if target:
        target.write_text(text, encoding="utf-8", newline="\n")
    else:
        _emit_stdout(text)


def _load_json_file(path: str | Path) -> dict[str, Any]:
    resolved = _resolve_repo_path(path)
    try:
        return json.loads(resolved.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"{normalize_repo_path(path)}: invalid JSON: {exc}") from exc


def _tracked_current_docs() -> list[str]:
    return sorted(path for path in git_lines("ls-files", "docs") if path.startswith("docs/"))


def _path_exists(path: str) -> bool:
    return _resolve_repo_path(path).exists()


def _uses_forward_slashes(path: str) -> bool:
    return "\\" not in path


def check_registry(registry_path: str = REGISTRY_PATH) -> list[str]:
    problems: list[str] = []
    registry_file = _resolve_repo_path(registry_path)
    if not registry_file.exists():
        return [f"{registry_path}: registry file is missing"]
    if registry_file.read_bytes().startswith(b"\xef\xbb\xbf"):
        problems.append(f"{registry_path}: must be UTF-8 without BOM")
    try:
        registry = _load_json_file(registry_path)
    except ValueError as exc:
        return [str(exc)]

    if registry.get("schema_version") != SUPPORTED_SCHEMA_VERSION:
        problems.append(f"{registry_path}: unsupported schema_version {registry.get('schema_version')!r}")
    docs_agents = _resolve_repo_path("docs/AGENTS.md")
    if not docs_agents.is_file():
        problems.append("docs/AGENTS.md: file is missing")
    else:
        budget = registry.get("docs_agents_budget", {})
        max_lines = int(budget.get("max_lines", 0))
        max_bytes = int(budget.get("max_bytes", 0))
        lines = len(docs_agents.read_text(encoding="utf-8").splitlines())
        byte_count = len(docs_agents.read_bytes())
        if max_lines and lines > max_lines:
            problems.append(f"docs/AGENTS.md: {lines} lines exceeds {max_lines}")
        if max_bytes and byte_count > max_bytes:
            problems.append(f"docs/AGENTS.md: {byte_count} bytes exceeds {max_bytes}")
    root_agents = _resolve_repo_path("AGENTS.md")
    if not root_agents.is_file() or "docs/AGENTS.md" not in root_agents.read_text(encoding="utf-8"):
        problems.append("AGENTS.md: missing route to docs/AGENTS.md")

    allowed_types = set(registry.get("allowed_document_types", []))
    allowed_statuses = set(registry.get("allowed_lifecycle_statuses", []))
    allowed_actions = set(registry.get("allowed_proposed_actions", []))
    if allowed_types != ALLOWED_DOCUMENT_TYPES:
        problems.append(f"{registry_path}: allowed_document_types do not match supported set")
    if allowed_statuses != ALLOWED_LIFECYCLE_STATUSES:
        problems.append(f"{registry_path}: allowed_lifecycle_statuses do not match supported set")
    if allowed_actions != ALLOWED_PROPOSED_ACTIONS:
        problems.append(f"{registry_path}: allowed_proposed_actions do not match supported set")

    documents = registry.get("documents", [])
    if not isinstance(documents, list):
        return sorted(problems + [f"{registry_path}: documents must be a list"])
    by_path: dict[str, dict[str, Any]] = {}
    for doc in documents:
        path = doc.get("path")
        if not path:
            problems.append(f"{registry_path}: document missing path")
            continue
        if path in by_path:
            problems.append(f"{path}: duplicate document path")
        by_path[path] = doc
        if not _path_exists(path):
            problems.append(f"{path}: document path missing")
        document_type = doc.get("document_type")
        lifecycle_status = doc.get("lifecycle_status")
        proposed_action = doc.get("proposed_action")
        if document_type not in ALLOWED_DOCUMENT_TYPES:
            problems.append(f"{path}: invalid document_type {document_type!r}")
        if lifecycle_status not in ALLOWED_LIFECYCLE_STATUSES:
            problems.append(f"{path}: invalid lifecycle_status {lifecycle_status!r}")
        if proposed_action not in ALLOWED_PROPOSED_ACTIONS:
            problems.append(f"{path}: invalid proposed_action {proposed_action!r}")
        replacement = doc.get("replacement_path")
        if replacement and not _path_exists(replacement):
            problems.append(f"{path}: replacement_path does not exist: {replacement}")
        reason = str(doc.get("reason") or "").strip()
        if proposed_action == "delete" or lifecycle_status == "delete_candidate":
            if not reason:
                problems.append(f"{path}: delete candidate requires non-empty reason")
            if doc.get("human_confirmation_required") is not True:
                problems.append(f"{path}: delete candidate requires human_confirmation_required=true")
        if doc.get("unique_source_risk") is True and proposed_action == "delete":
            problems.append(f"{path}: unique_source_risk=true cannot use proposed_action=delete")
        if document_type == "generated_view" and not doc.get("generator_candidates") and lifecycle_status != "needs_human_confirmation":
            problems.append(f"{path}: generated_view requires generator_candidates or needs_human_confirmation")
        if document_type == "canonical_spec" and lifecycle_status == "active" and proposed_action == "delete":
            problems.append(f"{path}: active canonical document cannot be marked delete")
        for field in ("inbound_references", "referenced_by_tests", "generator_candidates"):
            for candidate in doc.get(field, []):
                if not _path_exists(candidate):
                    problems.append(f"{path}: {field} path does not exist: {candidate}")

    expected_docs = set(_tracked_current_docs()) - {normalize_repo_path(registry_path)}
    actual_docs = set(by_path)
    for missing in sorted(expected_docs - actual_docs):
        problems.append(f"{missing}: tracked docs file is not covered by docs registry")
    for extra in sorted(actual_docs - expected_docs):
        problems.append(f"{extra}: registry path is not a tracked docs file")

    exact_groups: dict[str, list[str]] = defaultdict(list)
    for doc in documents:
        group = doc.get("duplicate_group") or doc.get("exact_duplicate_group")
        if group:
            exact_groups[str(group)].append(doc.get("path", ""))
    for group, paths in sorted(exact_groups.items()):
        if len(paths) < 2:
            problems.append(f"{registry_path}: duplicate group {group} has fewer than two members")

    archived_paths = registry.get("archived_document_paths", {})
    if archived_paths is None:
        archived_paths = {}
    if not isinstance(archived_paths, dict):
        problems.append(f"{registry_path}: archived_document_paths must be an object")
    else:
        new_to_old: dict[str, list[str]] = defaultdict(list)
        for old_path, new_path in archived_paths.items():
            if not isinstance(old_path, str) or not isinstance(new_path, str):
                problems.append(f"{registry_path}: archived_document_paths entries must map strings to strings")
                continue
            new_to_old[new_path].append(old_path)
            if not _uses_forward_slashes(old_path) or not _uses_forward_slashes(new_path):
                problems.append(f"{old_path}: archived_document_paths must use forward slashes")
            if not old_path.startswith("docs/") or old_path.startswith("docs/archive/") or "/../" in old_path:
                problems.append(f"{old_path}: archived old path must be a retired docs path outside docs/archive/")
            if not new_path.startswith("docs/archive/"):
                problems.append(f"{old_path}: archived path must be under docs/archive/: {new_path}")
            if _path_exists(old_path):
                problems.append(f"{old_path}: archived old path still exists")
            if not _path_exists(new_path):
                problems.append(f"{old_path}: archived path does not exist: {new_path}")
            if old_path in by_path:
                problems.append(f"{old_path}: archived old path is still registered as a document")
            new_doc = by_path.get(new_path)
            if new_doc is None:
                problems.append(f"{old_path}: archived path is not registered as a document: {new_path}")
                continue
            if new_doc.get("lifecycle_status") != "historical":
                problems.append(f"{new_path}: archived document must use lifecycle_status=historical")
            if new_doc.get("proposed_action") != "keep":
                problems.append(f"{new_path}: archived document must use proposed_action=keep")
            if new_doc.get("human_confirmation_required") is not False:
                problems.append(f"{new_path}: archived document must use human_confirmation_required=false")
        for new_path, old_values in sorted(new_to_old.items()):
            if len(old_values) > 1:
                problems.append(f"{new_path}: archived path is mapped from multiple old paths")

    return sorted(set(problems))


def _count_by(documents: list[dict[str, Any]], field: str) -> dict[str, int]:
    return dict(sorted(Counter(str(doc.get(field)) for doc in documents).items()))


def _table(rows: list[list[str]]) -> list[str]:
    if not rows:
        return ["无。"]
    header = "| " + " | ".join(rows[0]) + " |"
    divider = "| " + " | ".join("---" for _ in rows[0]) + " |"
    body = ["| " + " | ".join(str(cell).replace("\n", "<br>") for cell in row) + " |" for row in rows[1:]]
    return [header, divider, *body]


def build_report(registry_path: str = REGISTRY_PATH) -> str:
    registry = _load_json_file(registry_path)
    documents = sorted(registry.get("documents", []), key=lambda item: item["path"])
    type_counts = _count_by(documents, "document_type")
    status_counts = _count_by(documents, "lifecycle_status")
    action_counts = _count_by(documents, "proposed_action")
    exact_groups = defaultdict(list)
    normalized_groups = defaultdict(list)
    for doc in documents:
        if doc.get("duplicate_group") or doc.get("exact_duplicate_group"):
            exact_groups[doc.get("duplicate_group") or doc.get("exact_duplicate_group")].append(doc["path"])
        if doc.get("normalized_duplicate_group"):
            normalized_groups[doc["normalized_duplicate_group"]].append(doc["path"])

    def docs_for(action: str | None = None, status: str | None = None) -> list[dict[str, Any]]:
        return [
            doc
            for doc in documents
            if (action is None or doc.get("proposed_action") == action)
            and (status is None or doc.get("lifecycle_status") == status)
        ]

    def unique_docs(items: list[dict[str, Any]]) -> list[dict[str, Any]]:
        by_path = {doc["path"]: doc for doc in items}
        return [by_path[path] for path in sorted(by_path)]

    archive_docs = docs_for(action="archive")
    delete_docs = docs_for(action="delete")
    review_docs = unique_docs(docs_for(action="review") + docs_for(status="needs_human_confirmation"))
    archived_map = registry.get("archived_document_paths") or {}
    archived_docs = [doc for old_path, new_path in sorted(archived_map.items()) for doc in documents if doc["path"] == new_path]
    candidate_paths = {doc["path"] for doc in archive_docs + delete_docs + review_docs + archived_docs}

    candidate_header = [
        "path",
        "type",
        "proposed action",
        "replacement / generator",
        "inbound refs",
        "unique risk",
        "reason",
        "human confirmation",
    ]

    def candidate_rows(items: list[dict[str, Any]]) -> list[list[str]]:
        rows = [candidate_header]
        for doc in items:
            replacement = doc.get("replacement_path") or ", ".join(doc.get("generator_candidates", [])) or "-"
            rows.append(
                [
                    doc["path"],
                    doc["document_type"],
                    doc["proposed_action"],
                    replacement,
                    str(len(doc.get("inbound_references", []))),
                    str(bool(doc.get("unique_source_risk"))).lower(),
                    doc.get("reason", ""),
                    str(bool(doc.get("human_confirmation_required"))).lower(),
                ]
            )
        return rows

    lines: list[str] = [
        "# 文档治理盘点报告",
        "",
        "本报告由 docs registry 生成，用于当前文档生命周期与治理状态审阅。",
        "",
        "## 1. 执行摘要",
        "",
        f"- 基线 ref：`{registry.get('baseline_ref')}`。",
        f"- 基线 commit：`{registry.get('baseline_sha')}`。",
        f"- docs registry 覆盖文档数：{len(documents)}。",
        "- 候选动作和已归档映射均以 registry 当前状态为准；归档不是删除。",
        "",
        "## 2. docs 总体统计",
        "",
        "### document type",
        "",
        *_table([["document_type", "count"], *[[key, str(value)] for key, value in type_counts.items()]]),
        "",
        "### lifecycle status",
        "",
        *_table([["lifecycle_status", "count"], *[[key, str(value)] for key, value in status_counts.items()]]),
        "",
        "### proposed action",
        "",
        *_table([["proposed_action", "count"], *[[key, str(value)] for key, value in action_counts.items()]]),
        "",
        "## 3. 分类口径",
        "",
        "- `canonical_spec`、`operational_guide` 和仍被 README、AGENTS、scripts、tests 引用的当前设计默认保留。",
        "- `generated_view` 只登记 generator 候选；不能用手改文档替代修改生成器。",
        "- 审计、迁移和日期快照先进入 historical 或 archive candidate；无引用不等于无价值。",
        "- `delete_candidate` 仅表示后续低风险删除审查对象，仍必须人工确认。",
        "",
        "## 4. 当前 canonical specs 清单",
        "",
        *_table([["path", "reason"], *[[doc["path"], doc["reason"]] for doc in documents if doc["document_type"] == "canonical_spec"]]),
        "",
        "## 5. 当前 operational guides 清单",
        "",
        *_table([["path", "reason"], *[[doc["path"], doc["reason"]] for doc in documents if doc["document_type"] == "operational_guide"]]),
        "",
        "## 6. generated views 清单及 generator",
        "",
        *_table([["path", "generator candidates", "reason"], *[[doc["path"], ", ".join(doc.get("generator_candidates", [])) or "-", doc["reason"]] for doc in documents if doc["document_type"] == "generated_view"]]),
        "",
        "## 7. historical / audit / migration records 清单",
        "",
        *_table([["path", "type", "status", "reason"], *[[doc["path"], doc["document_type"], doc["lifecycle_status"], doc["reason"]] for doc in documents if doc["document_type"] in {"historical_snapshot", "audit_record", "migration_record"} and doc["path"] not in candidate_paths]]),
        "",
        "## 8. archive candidates",
        "",
        *_table(candidate_rows(archive_docs)),
        "",
        "## 9. delete candidates",
        "",
        *_table(candidate_rows(delete_docs)),
        "",
        "## 10. needs human confirmation",
        "",
        *_table(candidate_rows(review_docs)),
        "",
        "## 11. 已归档文档",
        "",
        *_table(
            [
                ["old path", "archived path", "type", "lifecycle status", "reason"],
                *[
                    [
                        old_path,
                        doc["path"],
                        doc["document_type"],
                        doc["lifecycle_status"],
                        doc["reason"],
                    ]
                    for old_path, new_path in sorted(archived_map.items())
                    for doc in documents
                    if doc["path"] == new_path
                ],
            ]
        ),
        "",
        "## 12. 重复组",
        "",
        "### exact duplicates",
        "",
        *_table([["group", "paths"], *[[group, "<br>".join(paths)] for group, paths in sorted(exact_groups.items())]]),
        "",
        "### normalized duplicates",
        "",
        *_table([["group", "paths"], *[[group, "<br>".join(paths)] for group, paths in sorted(normalized_groups.items())]]),
        "",
        "## 13. 引用断链或异常",
        "",
    ]
    problems = check_registry(registry_path)
    lines.extend(["- docs_tool check 当前通过，未发现 registry 引用断链。" if not problems else "- " + "\n- ".join(problems)])
    lines.extend(
        [
            "",
            "## 14. unique source 风险",
            "",
            *_table([["path", "action", "reason"], *[[doc["path"], doc["proposed_action"], doc["reason"]] for doc in documents if doc.get("unique_source_risk") and doc["path"] not in candidate_paths]]),
            "",
            "## 15. 后续推荐执行批次",
            "",
            f"- Batch A：低风险删除候选，{len(delete_docs)} 个。仅处理精确重复、可重建或有明确 replacement 的项目。",
            f"- Batch B：历史归档候选，{len(archive_docs)} 个。保留审计或决策价值，移动到 archive，不删除。",
            f"- Batch C：需人工确认，{len(review_docs)} 个。不在 Codex 自动清理范围内。",
            "",
            "## 16. 范围声明",
            "",
            "当前治理报告仅描述 docs 生命周期与归档状态；未将 archive 视为删除，也不改变 data、exports、数据库或 SQLite 文件。",
            "",
        ]
    )
    return "\n".join(lines)


def write_report(registry_path: str, output: str | None) -> None:
    text = build_report(registry_path)
    target = _ensure_tmp_output(output)
    if target:
        target.write_text(text, encoding="utf-8", newline="\n")
    else:
        _emit_stdout(text + "\n")


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Docs lifecycle inventory and governance checks.")
    subparsers = parser.add_subparsers(dest="command", required=True)
    inventory = subparsers.add_parser("inventory", help="Build docs inventory JSON.")
    inventory.add_argument("--ref", default="origin/GPT")
    inventory.add_argument("--output")
    check = subparsers.add_parser("check", help="Validate docs registry and docs governance rules.")
    check.add_argument("--registry", default=REGISTRY_PATH)
    report = subparsers.add_parser("report", help="Build Markdown docs governance report from registry.")
    report.add_argument("--registry", default=REGISTRY_PATH)
    report.add_argument("--output")
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    try:
        if args.command == "inventory":
            write_json(build_inventory(args.ref), args.output)
        elif args.command == "check":
            problems = check_registry(args.registry)
            if problems:
                for problem in problems:
                    _emit_stderr(problem)
                return 1
        elif args.command == "report":
            write_report(args.registry, args.output)
        else:  # pragma: no cover
            raise AssertionError(f"unknown command: {args.command}")
    except Exception as exc:
        _emit_stderr(f"error: {exc}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
